export type Owner = { id: string; name?: string };
export type EmploymentStatus = 'active' | 'resigned' | 'unused' | 'unknown';
export type Person = Owner & { department: string; employment_status?: EmploymentStatus };
export const employmentNames: Record<EmploymentStatus, string> = { active: '在职', resigned: '已离职', unused: '暂不使用', unknown: '待确认' };
export const isUnavailable = (person?: Person) => person?.employment_status === 'resigned' || person?.employment_status === 'unused';
export type AppSettings = { revision: number; profile: { name: string; owner_id: string }; people: Person[] };
export const defaultSettings: AppSettings = { revision: 0, profile: { name: '', owner_id: '' }, people: [] };
export type State = 'todo' | 'active' | 'done' | 'paused' | 'closed';
export type SyncField = 'title' | 'start' | 'end' | 'owners' | 'state' | 'priority';
export type Task = {
  personal_quadrant?: Quadrant;
  acceptance?: string;
  priority?: string;
  id: string; project: string; title: string; start: string; end: string; owners: Owner[]; state: State;
  module: string; version: string; source: null | { record_id: string; scope: string; base: Record<string, unknown>; missing?: boolean };
  departments: string[]; department_override: string[] | null;
  linked: boolean; upstream: string[]; branch_of: string | null; prototypes: boolean; revision: number;
  workflow_stage?: number | null; workflow_parent?: string | null; module_local?: boolean;
  readiness: 'blocked' | 'ready'; blocked_by: string[];
  pending: Partial<Record<SyncField, { before: unknown; after: unknown }>>;
  conflicts: Partial<Record<SyncField, { base: unknown; local: unknown; remote: unknown }>>;
};
export type WorkflowColumn = { id: string; name: string; priority: '' | 'high' | 'medium' | 'low'; archived_tasks?: string[] };
export type Project = {
  version_catalog?: { field: string; selectable: boolean; options: string[] };
  priority_catalog?: { field: string; selectable: boolean; options: string[] };
  archived?: boolean;
  workflow_columns?: WorkflowColumn[];
  id: string; name: string; base_token: string; table_id: string; url?: string;
  fields: Record<string, string>; targets: Record<string, string>;
  target_details?: Record<string, { milestone: string; description: string }>;
  current_target?: string;
  version_overview?: Array<Pick<VersionOverviewRow, 'id'> & Partial<VersionOverviewRow> & { released?: string }>;
  version_overview_removed?: string[];
  department_catalog?: DepartmentCatalog;
  done_value?: string; todo_value?: string; active_value?: string; paused_value?: string; closed_value?: string;
  sources?: Partial<Record<'tests' | 'versions', ProjectSource>>;
  source_refresh?: Array<'tests' | 'versions'>;
  source_cache?: { tests?: SourceCache & { windows?: TestWindow[] }; versions?: SourceCache & { rows?: OnlineVersion[]; online?: Record<'android' | 'ios', OnlineVersion | null> } };
};
export type ProjectSource = { url: string; base_token?: string; table_id?: string; project_value?: string; online_value?: string; fields?: Record<string, string> };
export type SourceCache = { updated_at?: string; error?: string };
export type TestWindow = { id: string; project: string; title: string; start: string; end: string; version?: string };
export type OnlineVersion = { id: string; platform: string; version: string; status: string; released: string; submitted?: string; description?: string };
export type VersionOverviewRow = { id: string; version: string; platform: string; submitted: string; description: string; status: string; origin: 'source' | 'legacy' | 'local' };
export type DepartmentOption = { id: string; name: string; color: number | null };
export type DepartmentCatalog = { field: string; options: DepartmentOption[]; error: string };
export type Candidate = { upstream: string; downstream: string; reason: string };
export type Auth = { configured?: boolean; authorized?: boolean; authenticated?: boolean; connected?: boolean; app_id?: string; redirect_uri?: string; [key: string]: unknown };
export type Quadrant = 'ui' | 'nui' | 'uni' | 'nuni';
export type PersonalBoardConfig = { sync: boolean; names: Record<Quadrant, string> };
export const defaultPersonalBoard: PersonalBoardConfig = { sync: false, names: { ui: '重要且紧急', nui: '重要不紧急', uni: '紧急不重要', nuni: '不重要不紧急' } };
export type Creation = { kind: 'requirement' | 'task'; id: string; project: string; title: string; module: string; revision: number; retry: boolean; created_at: number; parents?: Array<{ id: string; title: string; version: string; owners: Owner[]; start: string; end: string }>; values: { title: string; start: string; end: string; owners: Owner[]; state: State; version: string; departments: string[]; parent_id?: string } };
export type Snapshot = { tasks: Task[]; projects: Project[]; candidates: Candidate[]; creations?: Creation[]; ignored_creations?: Creation[]; auth: Auth; settings: AppSettings; personal_board?: PersonalBoardConfig };
export const stateNames: Record<State, string> = { todo: '未开始', active: '进行中', done: '交付就绪', paused: '暂停', closed: '已关闭' };
export const fieldNames: Record<SyncField, string> = { title: '标题', start: '开始时间', end: '截止时间', owners: '处理人', state: '完成／流转状态', priority: '优先级' };
export type Run = <T = unknown>(method: string, params?: Record<string, unknown>, message?: string) => Promise<T | undefined>;

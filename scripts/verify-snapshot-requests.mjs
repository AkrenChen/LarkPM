import assert from 'node:assert/strict';
import { SnapshotRequests } from '../src/snapshotRequests.ts';

const deferred = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };
const requests = new SnapshotRequests();
const old = deferred(), next = deferred();
let calls = 0;
const load = () => ++calls === 1 ? old.promise : next.promise;
const first = requests.run('a', load);
const duplicate = requests.run('a', load);
assert.equal(calls, 1);
const fresh = requests.run('a', load, true);
assert.equal(calls, 1);
assert.equal(await requests.run('b', async () => 'other project'), 'other project');
old.resolve('before mutation');
assert.equal(await first, 'before mutation');
assert.equal(await duplicate, 'before mutation');
await Promise.resolve();
assert.equal(calls, 2);
next.resolve('after mutation');
assert.equal(await fresh, 'after mutation');
assert.equal(await requests.run('a', async () => 'later'), 'later');
const failed = deferred();
const bad = requests.run('c', () => failed.promise);
const retry = requests.run('c', async () => 'recovered', true);
failed.reject(Error('offline'));
await assert.rejects(bad, /offline/);
assert.equal(await retry, 'recovered');
console.log('Snapshot requests: deduplicated, fresh after mutation, project isolation, failure recovery passed');

import assert from 'node:assert/strict';
import { StableRequirementOrder, feedColumnCount } from '../src/feedLayout.ts';

assert.equal(feedColumnCount(329), 1);
assert.equal(feedColumnCount(671), 1);
assert.equal(feedColumnCount(672), 2);
assert.equal(feedColumnCount(1360), 4);
assert.equal(feedColumnCount(1700), 5);
const order = new StableRequirementOrder();
const task = (id, state = 'todo') => ({ id, state });
let result = order.update(['A', 'B', 'C'], [task('a'), task('b')], [], 'p');
assert.deepEqual(result.names, ['A', 'B', 'C']);
const initial = result.epoch;
result = order.update(['B', 'C', 'A'], [task('b'), task('a')], [], 'p');
assert.deepEqual(result.names, ['A', 'B', 'C']);
assert.equal(result.epoch, initial);
result = order.update(['B', 'C', 'A', 'D'], [task('b'), task('a'), task('new', 'active')], [], 'p');
assert.deepEqual(result.names, ['A', 'B', 'C', 'D']);
assert.equal(result.epoch, initial);
result = order.update(['B', 'C', 'A', 'D'], [task('b', 'active'), task('a'), task('new', 'active')], [], 'p');
assert.deepEqual(result.names, ['B', 'C', 'A', 'D']);
assert.ok(result.epoch > initial);
const changed = result.epoch;
result = order.update(['C', 'B', 'A', 'D'], [task('b', 'active'), task('a'), task('new', 'active')], [{ name: 'C', priority: 'high' }], 'p');
assert.deepEqual(result.names, ['C', 'B', 'A', 'D']);
assert.ok(result.epoch > changed);
result = order.update(['D', 'C'], [task('new', 'active')], [], 'p:filter');
assert.deepEqual(result.names, ['D', 'C']);
console.log('Adaptive full columns and stable requirement order across replacement/new tasks; explicit reordering passed');
